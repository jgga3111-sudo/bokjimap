import { services } from "@/data/services";

/**
 * 검색창을 눌렀을 때 보여줄 "많이 찾는 것".
 *
 * ── 왜 필요한가 ────────────────────────────────────────────────
 * 검색창에 `지원금 이름 검색`이라고만 적혀 있었다. 2026-09-04에 검색을 이름
 * 말고 **본문(지원내용·지원대상)까지** 뒤지도록 고쳐서 "백신"으로도 5건이
 * 나오는데, 화면 어디에도 그걸 알려 주는 곳이 없었다. 빈 검색창은 무엇을
 * 칠 수 있는지 말해 주지 않는다.
 *
 * 당근이 검색창 바로 밑에 「인기 검색어 에어컨 노트북 원룸」을 한 줄로 깔아
 * 두는 것이 같은 일을 한다(2026-09-05 실측).
 *
 * ── 자리를 차지하지 않는다 ─────────────────────────────────────
 * 헤더는 sticky라 한 줄이 늘면 모든 페이지에서 본문이 그만큼 줄어든다.
 * 그래서 화면에 늘 깔지 않고, **검색창을 눌렀을 때 뜨는 자리**에 넣는다.
 * 어차피 비어 있던 자리다.
 *
 * ── 서버에서만 부른다 ──────────────────────────────────────────
 * 여기서 `services`(2.9MB)를 읽는다. 클라이언트 컴포넌트가 이 파일을 import
 * 하면 그 덩어리가 통째로 브라우저 번들에 들어간다. **서버 컴포넌트에서
 * 읽어 prop으로 내려보낸다.** SearchBox는 이 파일을 모른다.
 *
 * 값은 손으로 적지 않는다 — `services`는 조회수 내림차순이라 앞에서 자르면
 * 그게 곧 많이 찾는 것이다. 수집이 늘면 목록도 따라 바뀐다.
 */
export type PopularItem = { id: string; name: string };

export const POPULAR: readonly PopularItem[] = services
  .slice(0, 5)
  .map((s) => ({ id: s.id, name: s.name }));
