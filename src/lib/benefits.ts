const BY_SLUG = new Map(BENEFITS.map((b) => [b.slug, b]));
export const benefitBySlug = (s: string) => BY_SLUG.get(s);

/** 이 서비스가 해당 혜택 종류에 속하는가. */
export const hasBenefit = (s: WelfareService, b: Benefit) =>
  s.payTypes.some((p) => b.values.includes(p));

export const servicesOf = (
  list: readonly WelfareService[],
  b: Benefit,
): WelfareService[] => list.filter((s) => hasBenefit(s, b));
