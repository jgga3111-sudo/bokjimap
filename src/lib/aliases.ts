/**
 * 사업의 **다른 이름**.
 *
 * ── 왜 만들었나 ────────────────────────────────────────────────
 * 조회수 294,386짜리 페이지의 제목이 「통합문화이용권」이었다. 그런데
 * 네이버 데이터랩으로 지난 1년을 재 보니(2026-09-07, 월 단위) 사람들이
 * 치는 말은 그게 아니었다.
 *
 *     문화누리카드    월평균 45.6   (2026년 2월 100)
 *     통합문화이용권  월평균  0.14  (2026년 2월 0.42)
 *
 * **320배다.** 공식명으로 검색하는 사람은 사실상 없다.
 *
 * 본문에는 "문화누리"가 열 번 나온다. 그런데 검색이 가장 크게 보는 자리
 * — 제목·h1·설명 — 에는 한 번도 없었다. 헤더 검색창은 더 심했다.
 * 가벼운 색인이 [id, 이름, 지역, 부처]뿐이라 "문화누리카드"를 치면 **0건**.
 *
 * 그리고 사이트가 스스로 어긋나 있었다. `lib/calendar.ts`는 처음부터
 * "문화누리카드(통합문화이용권)"로 적고 있었다.
 *
 * ── 규칙 ────────────────────────────────────────────────────────
 * · **원문이 함께 적어 놓은 이름만 싣는다.** 통합문화이용권 본문에
 *   "통합문화이용권(문화누리카드)을 발급하여"가 그대로 있다. 우리가
 *   별명을 지어 붙이는 자리가 아니다 — 그건 제도를 우리 말로 바꾸는
 *   일이고, 이 사이트가 하지 않기로 한 것이다(CLAUDE.md 3절).
 * · **검색량이 공식명을 넘을 때만 넣는다.** 통칭이 있다고 다 넣지 않는다.
 *   평생교육이용권은 통칭(평생교육바우처 7.9)보다 공식명(13.8)이 더 많이
 *   검색돼 넣지 않았다. 넣을 이유가 그것뿐이기 때문이다.
 * · 900건 전부를 훑어 이 조건에 걸린 것은 **이 하나였다.** 목록이 길어지면
 *   기준이 느슨해졌다는 뜻이니 위 두 줄을 다시 읽는다.
 *
 * ── 어디에 쓰이나 ──────────────────────────────────────────────
 * 상세 페이지의 <title>·설명·h1, 목록 카드, 그리고 검색 두 갈래
 * (`lib/search.ts` 헤더 색인 · `lib/searchFull.ts` 서버 전문검색).
 *
 * ⚠ 이 파일은 **아무것도 import하지 않는다.** `search.ts`가 클라이언트
 * 번들에 실리므로, 여기서 `@/data/services`를 끌어오면 2.9MB가 딸려
 * 들어간다(search.ts 머리말의 함정과 같다). 손으로 적는 표로 둔다.
 */

/** 사업 id → 같이 불리는 이름. 원문에 함께 적혀 있는 것만. */
export const ALIASES: Readonly<Record<string, readonly string[]>> = {
  /* 통합문화이용권 — 복지로 조회수 294,386.
     원문: "…통합문화이용권(문화누리카드)을 발급하여 개인당 문화누리카드
     1매 발급(연 15만원 지원…)합니다." */
  WLF00000055: ["문화누리카드"],
};

/**
 * 제목·목록에 쓰는 이름.
 *
 * 괄호에 넣는 것은 우리가 정한 표기가 아니라 **원문이 쓰는 표기**다.
 * 별칭이 없으면 이름을 그대로 돌려준다 — 899건은 여기서 아무 일도 없다.
 */
export function nameWithAlias(id: string, name: string): string {
  const alias = ALIASES[id];
  return alias && alias.length > 0 ? `${name}(${alias.join("·")})` : name;
}

/** 검색이 이름과 **같은 등급으로** 대조할 이름들. 원문이 함께 쓰는 이름이므로. */
export function searchableNames(id: string, name: string): readonly string[] {
  const alias = ALIASES[id];
  return alias && alias.length > 0 ? [name, ...alias] : [name];
}

/**
 * 헤더 색인용 — 색인 행의 id는 `WLF` 접두사가 없다(`data/searchIndex.ts`).
 * 질의마다 문자열을 이어 붙이지 않도록 모듈을 읽을 때 한 번만 만든다.
 */
export const ALIASES_BY_ROW_ID: ReadonlyMap<string, readonly string[]> = new Map(
  Object.entries(ALIASES).map(([id, list]) => [id.replace(/^WLF/, ""), list]),
);
