/**
 * 제목·목록에 쓰는 이름.
 *
 * 괄호에 넣는 것은 우리가 정한 표기가 아니라 **원문이 쓰는 표기**다.
 * 별칭이 없으면 이름을 그대로 돌려준다 — 899건은 여기서 아무 일도 없다.
 */
export function nameWithAlias(id: string, name: string): string {
  const alias = ALIASES[id];
  if (!alias || alias.length === 0) return name;
  const joined = alias.join("·");

  /* 이름이 이미 괄호로 끝나면 그 안에 잇는다. 「대중교통비 환급 지원
     (모두의카드)」에 그냥 붙이면 "…(모두의카드)(K-패스)"처럼 괄호가 두 번
     달린다. 원문의 낱말 순서는 건드리지 않고 뒤에 잇기만 한다. */
  return name.endsWith(")")
    ? `${name.slice(0, -1)}·${joined})`
    : `${name}(${joined})`;
}

/** 검색이 이름과 **같은 등급으로** 대조할 이름들. 원문이 함께 쓰는 이름이므로. */
export function searchableNames(id: string, name: string): readonly string[] {
  const alias = ALIASES[id];
  return alias && alias.length > 0 ? [name, ...alias] : [name];
}

/**
 * 헤더 색인용 — 색인 행의 id는 `WLF` 접두사가 없다(`data/searchIndex.ts`).
 * 질의마다 문자열을 이어 붙이지 않도록 모듈을 읽을 때 한 번만 만든다.
 */
export const ALIASES_BY_ROW_ID: ReadonlyMap<string, readonly string[]> = new Map(
  Object.entries(ALIASES).map(([id, list]) => [id.replace(/^WLF/, ""), list]),
);
