import type { WelfareService } from "@/types/welfare";

/**
 * 본문 문장에 적힌 **신청 기간**을 읽어낸다.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────────
 * 조회수 1위 청년내일저축계좌(1,285만)의 요약문은 이렇게 끝난다.
 *
 *     … 자산형성을 지원합니다. (2026년 모집기간: '26.5.4.(월) ~ '26.5.20.(수))
 *
 * 오늘이 9월인데 화면 어디에도 **끝났다는 말이 없다.** 이 페이지를 보고
 * 주민센터에 간 사람은 헛걸음한다. CLAUDE.md 3절은 "마감일이 지난 공고는
 * 숨기지 말고 마감으로 표기한다"고 정해 두었는데, 그 규칙이 구조화된
 * `applyEnd` 필드에만 걸려 있었다. 그런데 그 필드는 **570건 중 554건이
 * `9999-12-31`(상시)**이라 진짜 날짜가 거의 없다. 날짜는 필드가 아니라
 * 본문 문장 안에 들어 있었다.
 *
 * ── 기준일을 마감일로 읽지 않는다 ──────────────────────────────
 * 본문에서 2026년 날짜를 아무거나 집으면 틀린다. 실제로 걸렸던 것들:
 *
 *   · 대상포진 예방접종      "2026. 1. 1. 이후 출생" → 출생 기준일
 *   · 희망두배 청년통장      "(기준기간: 2025.6.1.~2026.5.31.)" → 소득 산정 기간
 *
 * 둘 다 마감일이 아니다. 여기에 "기간이 지났습니다"를 달면 그 자체가
 * 틀린 정보가 된다. 그래서 두 겹으로 좁힌다.
 *
 *   ① **범위 표현**이어야 한다(`~`로 이어진 시작~끝).  단일 날짜는 안 본다.
 *   ② 그 범위 **앞 40자 안에** 신청·모집·접수·공모·응모 + 기간/기한이
 *      붙어 있어야 한다.
 *
 * `기간:`처럼 두루뭉술한 조건을 쓰면 "기준기간:"이 걸려 들어온다. 앞말을
 * 열거로 못 박은 이유다. 지원기간·사용기간도 뺐다 — 받는 기간이지
 * 신청하는 기간이 아니다.
 *
 * 2026-09-06 수록 900건 실측: 9건이 걸리고, 오탐 0건.
 *
 * ── 날짜 비교는 여기서 하지 않는다 ─────────────────────────────
 * "지났는가"는 **오늘이 언제인가**에 달렸다. 정적 빌드에서 그걸 판정하면
 * 빌드한 날이 HTML에 굳어, 배포를 안 하는 동안 조용히 틀려 간다
 * (`ThisMonth`가 같은 함정을 피한 방식과 같다). 여기서는 **적혀 있는 끝날**
 * 까지만 내보내고, 오늘과의 비교는 브라우저에서 한다.
 */
export type StatedPeriod = {
  /** 본문에 적힌 신청 기간의 끝날. `YYYY-MM-DD`. */
  end: string;
  /** 화면에 그대로 보여줄 원문 조각. 우리가 고쳐 쓰지 않는다. */
  text: string;
};

/** 신청 기간임을 알리는 앞말. 이 열거를 넓히면 곧바로 오탐이 늘어난다. */
const PERIOD_WORD = /(모집|신청|접수|공모|응모)\s*(?:및\s*접수\s*)?(?:기간|기한)/;

/** `2026.3.30. ~ 5.29.` · `'26.5.4.(월) ~ '26.5.20.(수)` · `2026년 1월 2일 ~ 2026년 1월 30일` */
const RANGE =
  /['’]?(\d{2,4})\s*[.\-년]\s*(\d{1,2})\s*[.\-월]\s*(\d{1,2})\s*[.\-일]?\s*(?:\([^)]{0,6}\))?\s*[~\-–]\s*['’]?(\d{2,4})?\s*[.\-년]?\s*(\d{1,2})\s*[.\-월]\s*(\d{1,2})\s*[.\-일]?/g;

/** `'26` 두 자리 표기를 2026으로 편다. */
const fullYear = (v: string): number => {
  const y = Number(v);
  return y < 100 ? y + 2000 : y;
};

const pad = (n: number) => String(n).padStart(2, "0");

export function statedApplyPeriod(s: WelfareService): StatedPeriod | null {
  const body = [
    s.summary,
    s.outline,
    s.supportContent,
    s.applyMethod,
    s.eligibility,
  ]
    .filter(Boolean)
    .join("\n");
  if (!body) return null;

  let best: { end: string; text: string } | null = null;

  for (const m of body.matchAll(RANGE)) {
    const before = body.slice(Math.max(0, m.index - 40), m.index);
    if (!PERIOD_WORD.test(before)) continue;

    /* 끝쪽에 연도가 없으면(`2026.3.30. ~ 5.29.`) 시작 연도를 잇는다. */
    const y = fullYear(m[4] ?? m[1]);
    const mo = Number(m[5]);
    const d = Number(m[6]);
    if (mo < 1 || mo > 12 || d < 1 || d > 31) continue;

    const end = `${y}-${pad(mo)}-${pad(d)}`;

    /* 여러 기간이 적힌 사업이 있다(차수별 모집). **가장 늦은 것**을 쓴다 —
       하나라도 아직 안 지났으면 지났다고 말하면 안 되기 때문이다. */
    if (!best || end > best.end) {
      best = { end, text: m[0].trim().replace(/\s+/g, " ") };
    }
  }

  return best;
}


/* ────────────────────────────────────────────────────────────────
   본문에 적힌 **예정 시점**.

   ── 왜 따로 두나 ──────────────────────────────────────────────
   조회수 96위 청년미래적금(80,450)의 요약문이 이렇게 끝난다.

       … 자유롭게 납입 가능한 정부지원형 적금 상품입니다. 2026년 6월 예정

   오늘은 9월이다. 원본 API를 2026-09-07에 다시 받아 대조했지만 이 문장은
   **그대로였다** — 복지로가 아직 안 고쳤다. 위의 `statedApplyPeriod`는
   `~`로 이어진 **범위**만 보므로 이런 단일 시점은 걸리지 않는다.

   ── "예정"만 본다 ─────────────────────────────────────────────
   처음에는 `예정|시행|출시|오픈|개시`로 훑어 6건을 잡았다. 그런데 그중
   다섯이 이런 것이었다.

       "2025년 10월부터 교통비 지원사업 시행"   (강남구 교통비)
       "2023. 8. 10(개정 조례 시행"             (전입세대 이사비용)
       "2016.07.01.시행"                        (장애인 운전면허)

   **시행일이 지난 것은 정상이다.** 이미 시행 중이라는 뜻이지 문장이 낡은
   것이 아니다. 여기에 "이 시점은 지났습니다"를 달면 멀쩡한 사업이 문제
   있어 보인다 — 띠 자체가 틀린 정보가 된다. 아직 안 일어난 일을 가리키는
   말은 **"예정"뿐이고**, 그 말만 시점이 지나면 낡는다.

   2026-09-07 수록 900건 실측: 2건이 걸린다(청년미래적금 2026-06,
   참전명예수당 2026-10). 뒤엣것은 아직 안 지났다 — 11월이 되면 저절로
   뜬다. 이것이 판정을 브라우저에 맡긴 이유다.

   ── 그달이 다 가야 지난 것으로 본다 ───────────────────────────
   "2026년 6월 예정"은 6월 15일에 아직 안 지났다. 그래서 끝날을 **그달의
   마지막 날**로 잡는다. 위 `statedApplyPeriod`와 같은 모양(`StatedPeriod`)
   으로 내보내 같은 띠 컴포넌트가 받는다.
   ──────────────────────────────────────────────────────────── */

/** `2026년 6월 예정` · `'26.6. 지급 예정` — 앞말이 아니라 **뒷말**이 조건이다. */
const PLAN = /['’]?(\d{2,4})\s*[.\-년]\s*(\d{1,2})\s*[.\-월][^\n]{0,10}?예정/g;

/** 그달의 마지막 날. `new Date(y, m, 0)`은 m월의 말일이다(0=전달 마지막). */
const endOfMonth = (y: number, mo: number) =>
  `${y}-${pad(mo)}-${pad(new Date(y, mo, 0).getDate())}`;

export function statedPlan(s: WelfareService): StatedPeriod | null {
  const body = [
    s.summary,
    s.outline,
    s.supportContent,
    s.applyMethod,
    s.eligibility,
    s.selectionCriteria,
  ]
    .filter(Boolean)
    .join("\n");
  if (!body) return null;

  let best: StatedPeriod | null = null;

  for (const m of body.matchAll(PLAN)) {
    const y = fullYear(m[1]);
    const mo = Number(m[2]);
    if (mo < 1 || mo > 12) continue;
    if (y < 2000 || y > 2100) continue;

    const end = endOfMonth(y, mo);

    /* 여러 예정이 적혀 있으면 **가장 늦은 것**을 쓴다. 하나라도 아직
       안 왔으면 지났다고 말하면 안 된다(위 신청 기간과 같은 이유). */
    if (!best || end > best.end) {
      best = { end, text: m[0].trim().replace(/\s+/g, " ") };
    }
  }

  return best;
}
