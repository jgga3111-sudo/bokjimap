import type { WelfareService } from "@/types/welfare";

/**
 * 본문 문장에 적힌 **신청 기간**을 읽어낸다.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────────
 * 조회수 1위 청년내일저축계좌(1,285만)의 요약문은 이렇게 끝난다.
 *
 *     … 자산형성을 지원합니다. (2026년 모집기간: '26.5.4.(월) ~ '26.5.20.(수))
 *
 * 오늘이 9월인데 화면 어디에도 **끝났다는 말이 없다.** 이 페이지를 보고
 * 주민센터에 간 사람은 헛걸음한다. CLAUDE.md 3절은 "마감일이 지난 공고는
 * 숨기지 말고 마감으로 표기한다"고 정해 두었는데, 그 규칙이 구조화된
 * `applyEnd` 필드에만 걸려 있었다. 그런데 그 필드는 **570건 중 554건이
 * `9999-12-31`(상시)**이라 진짜 날짜가 거의 없다. 날짜는 필드가 아니라
 * 본문 문장 안에 들어 있었다.
 *
 * ── 기준일을 마감일로 읽지 않는다 ──────────────────────────────
 * 본문에서 2026년 날짜를 아무거나 집으면 틀린다. 실제로 걸렸던 것들:
 *
 *   · 대상포진 예방접종      "2026. 1. 1. 이후 출생" → 출생 기준일
 *   · 희망두배 청년통장      "(기준기간: 2025.6.1.~2026.5.31.)" → 소득 산정 기간
 *
 * 둘 다 마감일이 아니다. 여기에 "기간이 지났습니다"를 달면 그 자체가
 * 틀린 정보가 된다. 그래서 두 겹으로 좁힌다.
 *
 *   ① **범위 표현**이어야 한다(`~`로 이어진 시작~끝).  단일 날짜는 안 본다.
 *   ② 그 범위 **앞 40자 안에** 신청·모집·접수·공모·응모 + 기간/기한이
 *      붙어 있어야 한다.
 *
 * `기간:`처럼 두루뭉술한 조건을 쓰면 "기준기간:"이 걸려 들어온다. 앞말을
 * 열거로 못 박은 이유다. 지원기간·사용기간도 뺐다 — 받는 기간이지
 * 신청하는 기간이 아니다.
 *
 * 2026-09-06 수록 900건 실측: 9건이 걸리고, 오탐 0건.
 *
 * ── 날짜 비교는 여기서 하지 않는다 ─────────────────────────────
 * "지났는가"는 **오늘이 언제인가**에 달렸다. 정적 빌드에서 그걸 판정하면
 * 빌드한 날이 HTML에 굳어, 배포를 안 하는 동안 조용히 틀려 간다
 * (`ThisMonth`가 같은 함정을 피한 방식과 같다). 여기서는 **적혀 있는 끝날**
 * 까지만 내보내고, 오늘과의 비교는 브라우저에서 한다.
 */
export type StatedPeriod = {
  /** 본문에 적힌 신청 기간의 끝날. `YYYY-MM-DD`. */
  end: string;
  /** 화면에 그대로 보여줄 원문 조각. 우리가 고쳐 쓰지 않는다. */
  text: string;
};

/** 신청 기간임을 알리는 앞말. 이 열거를 넓히면 곧바로 오탐이 늘어난다. */
const PERIOD_WORD = /(모집|신청|접수|공모|응모)\s*(?:및\s*접수\s*)?(?:기간|기한)/;

/** `2026.3.30. ~ 5.29.` · `'26.5.4.(월) ~ '26.5.20.(수)` · `2026년 1월 2일 ~ 2026년 1월 30일` */
const RANGE =
  /['’]?(\d{2,4})\s*[.\-년]\s*(\d{1,2})\s*[.\-월]\s*(\d{1,2})\s*[.\-일]?\s*(?:\([^)]{0,6}\))?\s*[~\-–]\s*['’]?(\d{2,4})?\s*[.\-년]?\s*(\d{1,2})\s*[.\-월]\s*(\d{1,2})\s*[.\-일]?/g;

/** `'26` 두 자리 표기를 2026으로 편다. */
const fullYear = (v: string): number => {
  const y = Number(v);
  return y < 100 ? y + 2000 : y;
};

const pad = (n: number) => String(n).padStart(2, "0");

export function statedApplyPeriod(s: WelfareService): StatedPeriod | null {
  const body = [
    s.summary,
    s.outline,
    s.supportContent,
    s.applyMethod,
    s.eligibility,
  ]
    .filter(Boolean)
    .join("\n");
  if (!body) return null;

  let best: { end: string; text: string } | null = null;

  for (const m of body.matchAll(RANGE)) {
    const before = body.slice(Math.max(0, m.index - 40), m.index);
    if (!PERIOD_WORD.test(before)) continue;

    /* 끝쪽에 연도가 없으면(`2026.3.30. ~ 5.29.`) 시작 연도를 잇는다. */
    const y = fullYear(m[4] ?? m[1]);
    const mo = Number(m[5]);
    const d = Number(m[6]);
    if (mo < 1 || mo > 12 || d < 1 || d > 31) continue;

    const end = `${y}-${pad(mo)}-${pad(d)}`;

    /* 여러 기간이 적힌 사업이 있다(차수별 모집). **가장 늦은 것**을 쓴다 —
       하나라도 아직 안 지났으면 지났다고 말하면 안 되기 때문이다. */
    if (!best || end > best.end) {
      best = { end, text: m[0].trim().replace(/\s+/g, " ") };
    }
  }

  return best;
}
